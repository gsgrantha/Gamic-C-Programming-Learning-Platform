/**
 * Builds seed/problems3.js from seed/problems3.spec.js:
 * compiles every reference solution with gcc, records the real output as the expected output.
 *   npm run build:problems
 */
const fs = require('fs');
const path = require('path');
const { runCode } = require('../services/runner');
const { makeStarter, clean } = require('../seed/helpers');
const spec = require('../seed/problems3.spec');

const START = 30;                                   // first id → q30
const XP = { Easy: 20, Medium: 35, Hard: 50, Advanced: 80 };

(async () => {
  const out = [];
  for (let i = 0; i < spec.length; i++) {
    const [difficulty, title, brief, hint, solution, inputs] = spec[i];
    const src = clean(solution);
    const tests = [];
    for (const stdin of inputs) {
      const r = await runCode(src, stdin);
      if (!r.ok || r.error) { console.error(`✗ ${title}: ${r.error}`); process.exit(1); }
      tests.push({ stdin, stdout: r.stdout });
    }
    out.push({ pid: `q${START + i}`, order: START + i, difficulty, title, brief, hint, xp: XP[difficulty], starter: makeStarter(solution), solution: src, tests });
    process.stdout.write('.');
  }
  fs.writeFileSync(path.join(__dirname, '../seed/problems3.js'), '// GENERATED by scripts/build-problems.js — edit problems3.spec.js instead.\nmodule.exports = ' + JSON.stringify(out, null, 1) + ';\n');
  console.log(`\nWrote ${out.length} problems (q${START}–q${START + out.length - 1}).`);
})();
